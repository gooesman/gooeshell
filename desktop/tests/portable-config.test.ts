const cipher={available:async()=>true,encrypt:async(value:string)=>Buffer.from(value),decrypt:async(value:Buffer)=>value.toString()};
function stores(dir:string){return {store:new Store(dir),identities:new IdentityStore(dir,cipher),credentials:new CredentialStore(dir,cipher),commands:new CommandStore(dir)};}
test('encrypted portable configuration merges without overwriting existing connections',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'gooeshell-config-test-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const src=stores(path.join(root,'source')),dst=stores(path.join(root,'target'));
  const identity=await src.identities.save({name:'fixture',username:'alice',remember:'persistent',password:'fixture-identity-password'});
  await src.store.saveGroup({id:'group-1',name:'servers',icon:'cloud',order:0});
  const profile:HostProfile={id:'connection-1',name:'example',host:'fixture.invalid',port:22,username:'alice',auth:'password',rememberHost:true,encoding:'utf8',groupId:'group-1',loginIdentityId:identity.id};
  await src.store.saveConnection(profile,true);
  await src.store.setHostKeyPreference({host:'fixture.invalid',port:22,skipVerification:true});
  await src.credentials.save(profile,{remember:'persistent',sudoUsesLogin:false,sudoPassword:'fixture-sudo'});
  await src.commands.saveGroup({id:'command-group',name:'shell',order:0,connectionId:profile.id});
  await src.commands.saveCommand({id:'command-1',groupId:'command-group',name:'list',command:'ls',description:'',mode:'insert',confirmBeforeRun:false,order:0});
  const all = ordinarySelection(backupCatalog(await readPortableConfig(src.store,src.identities,src.commands)));
  const withSecrets={...all,secrets:true,hostPreferences:true};
  const publicData=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,all);
  assert(!JSON.stringify(publicData).includes('fixture-identity-password'));assert(!JSON.stringify(publicData).includes('fixture-sudo'));
  const complete=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,withSecrets);
  const encrypted=await encryptBackup(complete,'fixture-passphrase');assert(!encrypted.includes('fixture-sudo'));
  const restored=validatePortableConfig(await decryptBackup(encrypted,'fixture-passphrase'));
  const unavailableCipher={...cipher,available:async()=>false};const blockedStore=new Store(path.join(root,'blocked'));
  await assert.rejects(importPortableConfig(restored,blockedStore,new IdentityStore(path.join(root,'blocked'),unavailableCipher),new CredentialStore(path.join(root,'blocked'),unavailableCipher),new CommandStore(path.join(root,'blocked')),withSecrets),/系统加密存储不可用/);
  assert.equal((await blockedStore.connections()).length,0);
  const result=await importPortableConfig(restored,dst.store,dst.identities,dst.credentials,dst.commands,{...withSecrets,hostPreferences:false});
  assert.equal(result.added,1);const imported=(await dst.store.connections())[0];assert.equal(imported.id,profile.id);
  assert.equal((await dst.identities.snapshot(imported.loginIdentityId!)).password,'fixture-identity-password');
  assert.equal((await dst.credentials.get(imported)).sudoPassword,'fixture-sudo');
  const command=await dst.commands.library();assert.equal(command.groups[0].connectionId,imported.id);assert.equal(command.commands[0].command,'ls');
  const repeated=await importPortableConfig(restored,dst.store,dst.identities,dst.credentials,dst.commands,{...all,settings:[]});
  assert.equal(repeated.added,0);assert.equal(repeated.skipped,1);assert.equal((await dst.identities.metadata()).length,1);assert.equal((await dst.store.groups()).length,1);assert.equal((await dst.commands.library()).commands.length,1);
  assert.deepEqual(await dst.store.hostKeyPreferences(),[],'skip-verification preferences require separate opt-in');
  await importPortableConfig(restored,dst.store,dst.identities,dst.credentials,dst.commands,{...all,settings:[],hostPreferences:true});
  assert.deepEqual(await dst.store.hostKeyPreferences(),[{host:'fixture.invalid',port:22,skipVerification:true}]);
  const onlyCommands={...all,settings:[],groupIds:[],connectionIds:[],identityIds:[]};
  const commandBackup=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,onlyCommands);
  assert.deepEqual(commandBackup.connections,[]);
  await importPortableConfig(commandBackup,dst.store,dst.identities,dst.credentials,dst.commands,onlyCommands);
  assert.equal((await dst.commands.library()).groups.length,1);
  assert.equal((await dst.commands.library()).groups[0].connectionId,imported.id);
  const direct={...profile,id:'direct-original',loginIdentityId:undefined,groupId:undefined};await dst.store.saveConnection(direct,true);
  const duplicate=await dst.store.importConnection({...direct,id:'direct-import',name:'must not replace'},false);assert.equal(duplicate.added,false);assert.equal(duplicate.profile.name,'example');
  assert.throws(()=>validatePortableConfig({...restored,connections:[...restored.connections,restored.connections[0]]}),/重复标识/);
});

test('import does not replace credentials of an existing shared jump host',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'gooeshell-jump-import-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const src=stores(path.join(root,'src')),dst=stores(path.join(root,'dst'));
 const hop={id:'hop',name:'gateway',host:'gateway.invalid',port:22,username:'alice',auth:'password' as const,rememberHost:true,reuseConnection:true};
 const profile:HostProfile={id:'new',name:'new',host:'new.invalid',port:22,username:'alice',auth:'password',rememberHost:true,encoding:'utf8',jumpHost:hop};
 await src.store.saveConnection(profile,true);await src.credentials.save(jumpCredentialProfile(hop),{remember:'persistent',sudoUsesLogin:true,password:'imported'});
 await dst.store.saveConnection({...profile,id:'existing',host:'existing.invalid'},true);await dst.credentials.save(jumpCredentialProfile(hop),{remember:'persistent',sudoUsesLogin:true,password:'existing'});
 const all=ordinarySelection(backupCatalog(await readPortableConfig(src.store,src.identities,src.commands)));
 const backup=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,{...all,secrets:true});
 await importPortableConfig(backup,dst.store,dst.identities,dst.credentials,dst.commands,{...all,secrets:true});
 assert.equal((await dst.credentials.get(jumpCredentialProfile(hop))).password,'existing');
});

test('selective migration only exports selected records and explicitly included dependencies',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'gooeshell-scope-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const src=stores(path.join(root,'source')), dst=stores(path.join(root,'target'));
  const alice=await src.identities.save({name:'Alice login',username:'alice',remember:'persistent',password:'alice-secret'});
  const bob=await src.identities.save({name:'Gateway login',username:'bob',remember:'persistent',password:'bob-secret'});
  for (const id of ['east','west']) await src.store.saveGroup({id,name:id,order:0,icon:'cloud'});
  const profile:HostProfile={id:'a',name:'Alpha',host:'alpha.invalid',port:22,username:'old',auth:'password',encoding:'utf8',rememberHost:true,
    groupId:'east',loginIdentityId:alice.id,jumpHost:{id:'hop',host:'hop.invalid',name:'gateway',port:22,username:'old',auth:'password',rememberHost:true,reuseConnection:true,loginIdentityId:bob.id}};
  await src.store.saveConnection(profile,true);
  await src.store.saveConnection({...profile,id:'b',groupId:'west',name:'Other',host:'other.invalid'},false);
  const data=await readPortableConfig(src.store,src.identities,src.commands);
  const onlyA:BackupSelection={connectionIds:['a'],groupIds:[],identityIds:[],settings:[],hostPreferences:false,secrets:false,commands:false};
  const detached=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,onlyA);
  assert.deepEqual(detached.groups.map(g=>g.id),['east']);
  assert.deepEqual(detached.identities,[]);
  const p=detached.connections[0].profile;
  assert.equal(p.username,'alice');assert.equal(p.jumpHost!.username,'bob');
  assert.equal(p.loginIdentityId,undefined);assert.equal(p.jumpHost!.loginIdentityId,undefined);
  assert(!JSON.stringify(detached).includes('other.invalid'));
  assert.deepEqual(detached.settings,{});
  assert.throws(()=>selectPortableConfig(detached,{...onlyA,settings:['appearance']}),/范围已变化/);
  assert.throws(()=>selectPortableConfig(data,{...onlyA,connectionIds:['missing']}),/范围已变化/);
  const included=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,{...onlyA,identityIds:[bob.id],secrets:true});
  assert.deepEqual(included.identities.map(i=>i.password),['bob-secret']);
  assert(!JSON.stringify(included).includes('alice-secret'));
  assert.equal(included.connections[0].profile.jumpHost!.loginIdentityId,bob.id);
  await importPortableConfig(included,dst.store,dst.identities,dst.credentials,dst.commands,{...onlyA,identityIds:[bob.id]});
  assert.equal((await dst.identities.snapshot(bob.id)).password,undefined);
  assert.deepEqual((await dst.store.connections()).map(c=>[c.host,c.groupId,c.jumpHost?.loginIdentityId]),[['alpha.invalid','east',bob.id]]);
});

test('keyboard-only restore from a legacy full backup preserves every other setting',async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'gooeshell-keys-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const src=stores(path.join(root,'source')),dst=stores(path.join(root,'target'));
  const sourceSettings=await src.store.settings();
  await src.store.saveSettings({...sourceSettings,copyOnSelect:true,shortcuts:{...sourceSettings.shortcuts,paste:'Alt+V'}});
  const legacy={...await readPortableConfig(src.store,src.identities,src.commands),version:1};
  const config=validatePortableConfig(await decryptBackup(await encryptBackup(legacy,'test-passphrase'),'test-passphrase'));
  const only:BackupSelection={settings:['shortcuts'],connectionIds:[],groupIds:[],identityIds:[],commands:false,secrets:false,hostPreferences:false};
  const fragment=await collectPortableConfig(src.store,src.identities,src.credentials,src.commands,only);
  assert.deepEqual(Object.keys(fragment.settings).sort(),[...settingFields.shortcuts].sort());
  assert.deepEqual(backupCatalog(validatePortableConfig(fragment)).settings,['shortcuts']);
  assert.throws(()=>validatePortableConfig({...fragment,settings:{copyOnSelect:true}}),/不完整/);
  await dst.store.saveSettings({...await dst.store.settings(),theme:'light',fontSize:23,externalEditorPath:'local-editor'});
  const before=await dst.store.settings();
  await importPortableConfig(config,dst.store,dst.identities,dst.credentials,dst.commands,only);
  assert.deepEqual(await dst.store.settings(),{...before,...fragment.settings});
  assert.equal((await dst.store.settings()).shortcuts.paste,'Alt+V');
});
